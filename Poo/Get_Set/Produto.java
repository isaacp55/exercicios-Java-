package Get_Set;

 class Produto {

	private String nome;
	private double valor;
		
	public void setNome(String nome) {
		this.nome = nome;
	}
	
	public String getNome() {
		return nome;
	}
	
	public double getValor() {
		return valor;
	}
	
	public double setValor() {
		return valor;
	}
	
	public String setNome() {
		return nome;
	}
	
	public void setValor(double valor) {
		this.valor = valor;
	}
	
			
}
