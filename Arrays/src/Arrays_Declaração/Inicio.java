package Arrays_Declaração;

public class Inicio {

	public static void main(String[] args) {
		

       // Declarar e inicializar em uma única linha
		
		int[] numeros = {10, 20, 30, 40, 50};
		System.out.println(numeros[0]); // Saída: 10
		System.out.println(numeros[4]); // Saída: 50
		
		numeros[2] = 35; // Alterar o valor na posição 2
		System.out.println(numeros[2]); // Saída: 35

	}
}
